@Serializable
internal data class DocumentInsert(
    @SerialName("user_id") val userId: String,
    @SerialName("application_id") val applicationId: Long?,
    val kind: DocumentKind,
    val filename: String,
    @SerialName("storage_path") val storagePath: String,
    @SerialName("mime_type") val mimeType: String,
    @SerialName("size_bytes") val sizeBytes: Long,
) {
    companion object {
        fun copyOf(d: ClientDocument, applicationId: Long?) = DocumentInsert(
            userId = d.userId, applicationId = applicationId, kind = d.kind, filename = d.filename,
            storagePath = d.storagePath, mimeType = d.mimeType, sizeBytes = d.sizeBytes,
        )
    }
}

@Serializable
internal data class ShowingInsert(
    @SerialName("listing_id") val listingId: Long,
    val type: ShowingType,
    val status: ShowingStatus,
    @SerialName("starts_at") val startsAt: String,
    @SerialName("visitor_name") val visitorName: String,
    @SerialName("visitor_email") val visitorEmail: String,
    @SerialName("visitor_phone") val visitorPhone: String?,
    val notes: String?,
    @SerialName("created_by") val createdBy: String,
) {
    companion object {
        fun from(userId: String, v: VisitInput) = ShowingInsert(
            listingId = v.listingId,
            type = ShowingType.PRIVATE,
            status = ShowingStatus.SCHEDULED,
            startsAt = v.startsAt,
            visitorName = v.visitorName.trim(),
            visitorEmail = v.visitorEmail.trim(),
            visitorPhone = v.visitorPhone.blankToNull(),
            notes = v.notes.blankToNull(),
            createdBy = userId,
        )
    }
}

