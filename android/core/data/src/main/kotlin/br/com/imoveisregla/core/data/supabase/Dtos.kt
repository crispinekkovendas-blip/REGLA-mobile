// Insert / update payloads (snake_case). Never carry id / created_at / updated_at —
// those are generated by Postgres.

internal fun String?.blankToNull(): String? = this?.trim()?.takeIf { it.isNotEmpty() }

@Serializable
internal data class ProfileUpsert(
    @SerialName("user_id") val userId: String,
    @SerialName("full_name") val fullName: String,
    val email: String,
    val phone: String,
    val cpf: String?,
    @SerialName("birth_date") val birthDate: String?,
    val occupation: String?,
    @SerialName("employment_type") val employmentType: EmploymentType?,
    @SerialName("monthly_income") val monthlyIncome: Long?,
    val residents: Int,
    @SerialName("has_pets") val hasPets: Boolean,
) {
    companion object {
        fun from(userId: String, i: ClientProfileInput) = ProfileUpsert(
            userId = userId,
            fullName = i.fullName.trim(),
            email = i.email.trim(),
            phone = i.phone.trim(),
            cpf = i.cpf.blankToNull(),
            birthDate = i.birthDate.blankToNull(),
            occupation = i.occupation.blankToNull(),
            employmentType = i.employmentType,
            monthlyIncome = i.monthlyIncome,
            residents = i.residents,
            hasPets = i.hasPets,
        )
    }
}

@Serializable
internal data class ApplicationInsert(
    @SerialName("listing_id") val listingId: Long,
    @SerialName("user_id") val userId: String,
    val intent: ApplicationIntent,
    @SerialName("offered_price") val offeredPrice: Long,
    @SerialName("guarantee_type") val guaranteeType: GuaranteeType?,
    @SerialName("move_in_date") val moveInDate: String?,
    val message: String?,
) {
    companion object {
        fun from(userId: String, i: ApplicationInput) = ApplicationInsert(
            listingId = i.listingId,
            userId = userId,
            intent = i.intent,
            offeredPrice = i.offeredPrice,
            guaranteeType = i.guaranteeType,
            moveInDate = i.moveInDate.blankToNull(),
            message = i.message.blankToNull(),
        )
    }
}

